create table if not exists public.attendance_backups (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid(),
  class_id text not null,
  roll_no text not null,
  student_name text not null,
  attendance_date date not null,
  status text not null check (status in ('present', 'absent', 'late', 'excused')),
  sync_id uuid not null,
  source text not null default 'rollflow-web',
  updated_at timestamptz not null default now(),
  unique (owner_id, class_id, roll_no, attendance_date)
);

alter table public.attendance_backups enable row level security;

create policy "teachers insert their own attendance backups"
on public.attendance_backups for insert
to authenticated
with check ((select auth.uid()) = owner_id);

create policy "teachers update their own attendance backups"
on public.attendance_backups for update
to authenticated
using ((select auth.uid()) = owner_id)
with check ((select auth.uid()) = owner_id);

create policy "teachers read their own attendance backups"
on public.attendance_backups for select
to authenticated
using ((select auth.uid()) = owner_id);

grant select, insert, update on public.attendance_backups to authenticated;
grant usage, select on sequence public.attendance_backups_id_seq to authenticated;
